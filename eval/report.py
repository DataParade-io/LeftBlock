"""Render the results JSON as the Markdown report. Counts, rates and category names only."""

from eval import detectors, tiers

NAMES = {
    detectors.STOCK: "(a) gitleaks, stock config",
    detectors.LEFTBLOCK: "(b) gitleaks, LeftBlock ruleset",
    detectors.DEEP: "(c) deep scan",
    detectors.COMBINED: "(d) LeftBlock + deep scan",
}
ORDER = (detectors.STOCK, detectors.LEFTBLOCK, detectors.DEEP, detectors.COMBINED)


def pct(value):
    return "n/a" if value is None else "%.1f%%" % (100 * value)


def rate(r):
    """``63.2% (61.9-64.5)``."""
    if r is None or r["value"] is None:
        return "n/a"
    return "%s (%.1f-%.1f)" % (pct(r["value"]), 100 * r["lo"], 100 * r["hi"])


def counts(m, weighted):
    c = m["estimated"] if weighted else m["counts"]
    fmt = "%.0f" if weighted else "%d"
    return " / ".join(fmt % c[k] for k in ("tp", "fp", "fn"))


def table(headers, rows):
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def headline(section, weighted):
    rows = []
    for name in ORDER:
        entry = section["detectors"].get(name)
        if not entry:
            continue
        o, c = entry["overall"], entry["critical"]
        rows.append([NAMES[name], rate(o["recall"]), rate(o["precision"]), counts(o, weighted),
                     rate(c["recall"]), rate(c["precision"]), counts(c, weighted)])
    return table(["Detector", "Recall (95% CI)", "Precision (95% CI)", "TP / FP / FN",
                  "Critical recall", "Critical precision", "Critical TP / FP / FN"], rows)


def group_table(section):
    names = [n for n in ORDER if n in section["detectors"]]
    rows = []
    for group in tiers.CRITICAL_GROUPS:
        row = [group]
        for name in names:
            m = section["detectors"][name]["groups"][group]
            row.append("%s [%d]" % (rate(m["recall"]), m["counts"]["tp"] + m["counts"]["fn"]))
        rows.append(row)
    return table(["Critical group [true lines]"] + [NAMES[n] for n in names], rows)


def miss_table(section, name, limit=15, critical_only=False):
    """Categories with the most missed true lines for one detector."""
    entry = section["detectors"].get(name)
    if not entry:
        return "_Detector not run._"
    rows = []
    for category, m in entry["categories"].items():
        fn = m["counts"]["fn"]
        if fn == 0:
            continue
        group = tiers.group_of(category)
        if critical_only and not group:
            continue
        rows.append((fn, category, group or ("generic" if category in tiers.GENERIC else "-"), m))
    rows.sort(key=lambda r: (-r[0], r[1]))
    return table(["Category", "Tier group", "Missed (FN)", "Recall (95% CI)", "True lines"],
                 [[cat, grp, fn, rate(m["recall"]), m["counts"]["tp"] + m["counts"]["fn"]] for fn, cat, grp, m in rows[:limit]])


def rules_table(section, names):
    """Which rules produce the false positives (units on F lines) and the true ones."""
    rows = []
    for name in names:
        entry = section["detectors"].get(name)
        if not entry:
            continue
        r = entry["rules"]
        fmt = lambda pairs: ", ".join("`%s` %d" % (rule, n) for rule, n in pairs[:6]) or "none"
        rows.append([NAMES[name], fmt(r["false_positive_units"]), fmt(r["false_positive_units_critical"]), fmt(r["true_positive_units"])])
    return table(["Detector", "Rules behind false positives (labelled F lines hit)", "...critical tier only", "Rules behind true positives (labelled T lines hit)"], rows)


def adds_table(adds, weighted):
    key = "estimated" if weighted else "count"
    rows = []
    for category, v in adds["new_true_positives"]["by_category"].items():
        rows.append((v[key], category, tiers.group_of(category) or ("generic" if category in tiers.GENERIC else "-"), v["count"]))
    rows.sort(key=lambda r: (-r[0], r[1]))
    return table(["Category", "Tier group", "Extra true lines found (est. in full set)" if weighted else "Extra true lines found",
                  "Sampled lines"], [[cat, grp, ("%.0f" % v) if weighted else v, n] for v, cat, grp, n in rows[:20]])


def render(results):
    out = []
    version = results["leftblock_version"]
    out.append("# LeftBlock detection evaluation, v%s\n" % version)
    out.append("Generated by `python -m eval` (see `eval/README.md`). gitleaks %s; deep scan `openai/privacy-filter` with LeftBlock's defaults "
               "(labels secret/private_email/private_phone/private_address, threshold 0.9, built-in exclusions). "
               "Counts, rates and category names only: no values, no file contents, no dataset file paths.\n"
               % results["gitleaks_version"])
    datasets = results["datasets"]

    out.append("## How to read the numbers\n")
    out.append(
        "- **Unit.** One labelled line (a multi-line label such as a PEM key is one unit, hit when a finding overlaps any of its lines). "
        "True (T) and false (F) labels are scored; X (undecided) labels are excluded and counted.\n"
        "- **Hit.** A detector hits a unit when one of its findings overlaps the unit's lines. Recall = TP/(TP+FN); precision = TP/(TP+FP). "
        "Intervals are Wilson 95%% intervals.\n"
        "- **Precision is precision on labelled lines, not a false-alarm rate.** CredData's F lines are *candidate* lines that look like credentials "
        "(chosen by scanners and heuristics, then judged by people), so they are hard negatives. A detector's precision here is much lower than "
        "its precision on arbitrary code, and it says nothing about the other 19 million lines.\n"
        "- **Critical tier.** A unit is in the tier when any of its categories maps to one of: %s (mapping in `eval/tiers.py`). "
        "The generic categories (Key, Token, API, Secret, Auth, Credential) are not in the tier; they are in the \"broad\" tier in the JSON.\n"
        % ", ".join("`%s`" % g for g in tiers.CRITICAL_GROUPS))

    cd = datasets.get("creddata")
    if cd:
        u = cd["units"]
        out.append("## CredData\n")
        out.append("Samsung/CredData at commit `%s` (Apache-2.0; values are obfuscated to same-shape fakes). %d files with labels, "
                   "%d labelled lines scored (%d true, %d false; %d critical-tier true, %d critical-tier false). "
                   "**%d lines labelled X were excluded**; %d units are multi-line.\n"
                   % (cd["pin"][:12], u["files"], u["labelled_lines"], u["true"], u["false"], u["critical_true"], u["critical_false"],
                      u["excluded_x_lines"], u["multi_line_units"]))
        out.append("### Full files, every labelled line (gitleaks only)\n")
        out.append("The model cannot read 19 million lines, so (c) and (d) appear only in the sample below.\n")
        out.append(headline(cd["full_files"], weighted=False) + "\n")
        out.append("**Recall by critical group** (full files):\n")
        out.append(group_table(cd["full_files"]) + "\n")
        out.append("**Which rules produce the false positives** (labelled lines hit, sampled counts; LeftBlock's ruleset also flags personal data such as UUIDs, "
                   "emails and home paths on purpose, which a credential-only label set counts as false positives):\n")
        out.append(rules_table(cd["full_files"], (detectors.STOCK, detectors.LEFTBLOCK)) + "\n")
        out.append("**Biggest misses for (b), all categories** (by missed lines):\n")
        out.append(miss_table(cd["full_files"], detectors.LEFTBLOCK) + "\n")
        out.append("**Biggest misses for (b), critical tier only:**\n")
        out.append(miss_table(cd["full_files"], detectors.LEFTBLOCK, critical_only=True) + "\n")
        out.append("**What the LeftBlock ruleset adds over stock gitleaks** (extra true / false lines found by (b), not (a)): "
                   "%d true, %d false.\n" % (cd["full_files"]["adds"]["gitleaks-leftblock_over_gitleaks-stock"]["new_true_positives"]["count"],
                                              cd["full_files"]["adds"]["gitleaks-leftblock_over_gitleaks-stock"]["new_false_positives"]["count"])
                   if "gitleaks-leftblock_over_gitleaks-stock" in cd["full_files"]["adds"] else "")
        w = cd.get("windows")
        if w:
            s = w["sample"]
            out.append("### Deep-scan sample: all four detectors on the same context windows\n")
            out.append(
                "The model runs at about %.1f s per KB on CPU, so it reads ±%d-line windows around a sample of labelled lines: "
                "all %d critical-tier true lines (a census, weight 1) plus a stratified random sample of the rest "
                "(`--deep-sample %d`, at least %d per stratum; %d other lines), %d lines in all, in %d files, %.0f KB of text. "
                "Sampled lines carry the weight N/n of their stratum, so rates estimate the full-dataset values; "
                "intervals use the Kish effective sample size, so the sampling error is in them. "
                "The TP/FP/FN columns are population estimates. Gitleaks (a) and (b) ran on the same windows, so (b), (c) and (d) compare like with like.\n"
                % (w["seconds"].get(detectors.DEEP, 0) / max(s["model_kb"], 1), s["context_lines_radius"], s["critical_true_census"], cd["deep_sample_requested"], s["min_per_stratum"],
                   s["other_sampled"], s["units"], s["files"], s["model_kb"]))
            out.append(headline(w, weighted=True) + "\n")
            out.append("**Recall by critical group** (sample; critical true lines are a census):\n")
            out.append(group_table(w) + "\n")
            out.append("**Rules behind the sample's false and true positives** (sampled counts):\n")
            out.append(rules_table(w, ORDER) + "\n")
            adds = w["adds"]
            for key, label in (("deep-scan_over_gitleaks-leftblock", "deep scan (c) over LeftBlock (b)"),
                               ("leftblock+deep_over_gitleaks-leftblock", "(d) over (b)")):
                if key in adds:
                    a = adds[key]
                    out.append("**%s.** Extra true lines found: %d sampled, about %.0f in the full set (%d / %.0f in the critical tier). "
                               "Extra false positives: %d sampled, about %.0f in the full set (%d / %.0f critical tier).\n"
                               % (label, a["new_true_positives"]["count"], a["new_true_positives"]["estimated"],
                                  a["new_true_positives"]["critical_count"], a["new_true_positives"]["critical_estimated"],
                                  a["new_false_positives"]["count"], a["new_false_positives"]["estimated"],
                                  a["new_false_positives"]["critical_count"], a["new_false_positives"]["critical_estimated"]))
                    if key.startswith("deep"):
                        out.append("Unique true positives by category (c over b):\n")
                        out.append(adds_table(a, weighted=True) + "\n")
                        out.append("Extra false positives by category (c over b, sampled count): %s\n" % (
                            ", ".join("%s %d" % (c, v["count"]) for c, v in sorted(a["new_false_positives"]["by_category"].items(),
                                                                                  key=lambda kv: -kv[1]["count"])[:12]) or "none"))
            out.append("Seconds per detector on the sample: %s.\n" % ", ".join("%s %.0f s" % (NAMES[k], v) for k, v in w["seconds"].items() if k in NAMES))
        out.append("### Flags on lines CredData did not label\n")
        out.append("Gitleaks scanned the whole files, so it also flagged lines the dataset has no label for. These are **not** counted as false positives: "
                   "CredData labels only candidate lines, so an unlabelled line is unreviewed rather than known-clean, and some flags may be real credentials the "
                   "labelling missed. They are shown only to size the unreviewed noise.\n")
        rows = []
        for name in (detectors.STOCK, detectors.LEFTBLOCK):
            f = cd["unlabelled_flags"].get(name)
            if f:
                top = ", ".join("`%s` %d" % (r, n) for r, n in f["findings_by_rule_all"][:5])
                rows.append([NAMES[name], f["findings"], f["distinct_lines"], f["all_findings"], top])
        out.append(table(["Detector", "Findings on unlabelled lines", "Distinct lines", "All findings", "Most frequent rules (all findings)"], rows) + "\n")
        aws = cd["probes"]["aws_client_id"]
        out.append("### How CredData rewrote AWS access key ids\n")
        out.append(
            "`download_data.py` obfuscates every value to a same-shape fake. For the %d true \"AWS Client ID\" rows: **%d end in `EXAMPLE` and %d contain `example` in any case**, "
            "so the AWS documentation values that gitleaks allowlists are not used and no category is discounted for that reason. "
            "What the rewrite does do is keep the prefix and replace the tail with random letters and digits, which breaks the base32 alphabet "
            "(`A-Z2-7`) the gitleaks rule needs: %d keep a gitleaks-matchable shape, %d have a gitleaks prefix but a tail outside base32, "
            "and %d carry another IAM prefix (AIDA, AROA, APKA, ...) that the gitleaks AWS rule does not target at all (%d rows have no value position). "
            "The misses on this category therefore overstate real-world misses; the row below scores only the units that still have a matchable shape.\n"
            % (aws["labelled_t_rows"], aws["ends_with_EXAMPLE"], aws["contains_example_any_case"], aws["gitleaks_prefix_and_shape"],
               aws["gitleaks_prefix_but_tail_outside_base32"], aws["iam_id_prefix_not_covered_by_gitleaks"], aws["value_position_missing"]))
        rows = []
        for name in (detectors.STOCK, detectors.LEFTBLOCK):
            entry = cd["full_files"]["detectors"].get(name)
            if entry:
                allc = entry["categories"].get("AWS Client ID")
                sub = entry.get("subsets", {}).get("AWS Client ID, key still gitleaks-shaped")
                rows.append([NAMES[name], rate(allc["recall"]) if allc else "n/a", rate(sub["recall"]) if sub else "n/a",
                             (sub["counts"]["tp"] + sub["counts"]["fn"]) if sub else 0])
        out.append(table(["Detector (full files)", "Recall, all AWS Client ID lines", "Recall, shape-valid lines only", "Shape-valid lines"], rows) + "\n")

    gen = datasets.get("generated")
    if gen:
        u = gen["units"]
        out.append("## Generated LeftBlock corpus\n")
        out.append("%d files built at run time from seed %d: %d labelled lines (%d planted credentials, %d hard negatives). Every provider rule LeftBlock ships, "
                   "plus AWS, GitHub, Slack, Google, Stripe, PEM, JWT, database URLs and password assignments, in .py, .ts, .env, YAML, JSON, Markdown, .ipynb and shell, "
                   "each in a *named* form (provider-named variable) and a *bare* form (neutral name, only the key's shape gives it away). "
                   "Hard negatives are placeholders, UUIDs, hashes, documented example values and environment-variable references. "
                   "The deep scan reads every line of every file here.\n" % (u["files"], gen["seed"], u["labelled_lines"], u["true"], u["false"]))
        out.append(headline(gen["full_files"], weighted=False) + "\n")
        out.append("**Recall by critical group:**\n")
        out.append(group_table(gen["full_files"]) + "\n")
        for tag, title in (("flavour", "recall by flavour"), ("context", "recall by file context")):
            names = [n for n in ORDER if n in gen["tags"]]
            values = sorted({v for n in names for v in gen["tags"][n][tag]})
            rows = [[v] + [rate(gen["tags"][n][tag][v]["recall"]) if v in gen["tags"][n][tag] else "n/a" for n in names] for v in values]
            if rows:
                out.append("**Planted credentials, %s:**\n" % title)
                out.append(table([tag] + [NAMES[n] for n in names], rows) + "\n")
        names = [n for n in ORDER if n in gen["tags"]]
        kinds = sorted({v for n in names for v in gen["tags"][n]["negkind"]})
        rows = []
        for v in kinds:
            row = [v]
            for n in names:
                m = gen["tags"][n]["negkind"].get(v)
                row.append("%d of %d flagged" % (m["counts"]["fp"], m["counts"]["fp"] + m["counts"]["tn"]) if m else "n/a")
            rows.append(row)
        out.append("**Hard negatives flagged, by kind:**\n")
        out.append(table(["negative kind"] + [NAMES[n] for n in names], rows) + "\n")
        out.append("**Which rules produce the false positives:**\n")
        out.append(rules_table(gen["full_files"], ORDER) + "\n")
        out.append("**Per-category recall** (planted credentials):\n")
        cats = sorted({c for n in names for c, m in gen["full_files"]["detectors"][n]["categories"].items() if m["counts"]["tp"] + m["counts"]["fn"]})
        rows = []
        for c in cats:
            row = [c]
            for n in names:
                m = gen["full_files"]["detectors"][n]["categories"][c]
                row.append("%d/%d" % (m["counts"]["tp"], m["counts"]["tp"] + m["counts"]["fn"]))
            rows.append(row)
        out.append(table(["Category"] + [NAMES[n] for n in names], rows) + "\n")
        adds = gen["full_files"]["adds"]
        if "deep-scan_over_gitleaks-leftblock" in adds:
            a = adds["deep-scan_over_gitleaks-leftblock"]
            out.append("Deep scan over (b) on the generated corpus: %d extra true lines, %d extra false positives.\n"
                       % (a["new_true_positives"]["count"], a["new_false_positives"]["count"]))

    out.append("## Run\n")
    rows = []
    for name, d in datasets.items():
        rows.append([name, "%.0f s" % d["seconds_total"]])
    out.append(table(["Dataset", "Wall time"], rows) + "\n")
    out.append("## Caveats\n")
    out.append(
        "- **The model may have seen CredData in training.** OpenAI's Privacy Filter model card reports a CredData split, so (c) and (d) on CredData may be optimistic; "
        "the generated corpus is the cleaner test of the deep scan.\n"
        "- **Windows are not production.** The deep scan normally reads added lines of a diff. Here it reads ±5 lines around labelled lines, which is the same text "
        "with the same exclusions, but the labelled lines are over-represented compared with real diffs.\n"
        "- **A repeated line is one finding.** `deep.scan` reports one finding per distinct (rule, file, line text); the harness credits every window line with identical text.\n"
        "- **Critical-tier choices are judgment calls.** NKEY seeds, PASERK/PASETO tokens, OTP seeds and the generic categories are outside the tier; move them in `eval/tiers.py` if you disagree.\n"
        "- **Sampling.** Critical true lines are a census. Everything else in the deep-scan sample is a weighted stratified sample; see the intervals.\n")
    out.append("## Critical tier definition\n")
    for group, names in tiers.CRITICAL_GROUPS.items():
        out.append("- `%s`: %s" % (group, ", ".join(names)))
    out.append("")
    return "\n".join(out) + "\n"
